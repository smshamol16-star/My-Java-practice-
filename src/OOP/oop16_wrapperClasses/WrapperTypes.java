package OOP.oop16_wrapperClasses;

public class WrapperTypes {

    public static void main(String[] args){


        Integer x = 10;
        Double y = 20.0;
        Character c = '*';
        Boolean b = true;
                                                // primitive type
        System.out.println("Integer: "+ x);     // int
        System.out.println("Double: "+ y);      // double
        System.out.println("Character: "+ c);   // char
        System.out.println("Boolean: "+ b);     // boolean
    }
}
